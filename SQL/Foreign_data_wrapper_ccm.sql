CREATE EXTENSION IF NOT EXISTS postgres_fdw;

CREATE SERVER ccm21_server
  FOREIGN DATA WRAPPER postgres_fdw
  OPTIONS (host 'localhost', port '5432', dbname 'eda2.0');

DROP USER MAPPING FOR CURRENT_USER SERVER ccm21_server;
CREATE USER MAPPING FOR CURRENT_USER
  SERVER ccm21_server
  OPTIONS (user 'myuser', password 'mypassword');

CREATE SCHEMA IF NOT EXISTS ccm21;

IMPORT FOREIGN SCHEMA ccm21
  LIMIT TO (seaoutlets)
  FROM SERVER ccm21_server
  INTO ccm21;

ALTER SCHEMA ccm21 OWNER TO USERWGEEL;
GRANT USAGE ON SCHEMA ccm21 TO USER_READ_WGEEL;
ALTER FOREIGN TABLE ccm21.seaoutlets OWNER TO USERWGEEL;
GRANT SELECT ON TABLE ccm21.seaoutlets TO USER_READ_WGEEL;